// Writes public/config.js from environment variables, so no project keys live in the code.
// Netlify runs this on every deploy (see netlify.toml). Locally it also reads a .env file.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const envFile = new URL('.env', root);
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_PUBLISHABLE_KEY;
const missing = [!url && 'SUPABASE_URL', !key && 'SUPABASE_PUBLISHABLE_KEY'].filter(Boolean);
if (missing.length) {
  console.error(`Missing ${missing.join(' and ')}. Copy .env.example to .env (local) or set them in Netlify → Site configuration → Environment variables.`);
  process.exit(1);
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) console.warn(`Note: SUPABASE_URL looks unusual: ${url}`);
if (/^(sb_secret_|eyJ.*service_role)/.test(key)) {
  console.error('SUPABASE_PUBLISHABLE_KEY must be the publishable (public) key, never the secret/service_role key.');
  process.exit(1);
}

writeFileSync(new URL('public/config.js', root), `// Generated by scripts/write-config.mjs from environment variables. Do not edit or commit.
// The publishable key is meant to be public; data access is enforced by row-level security.
export const SUPABASE_URL = ${JSON.stringify(url)};
export const SUPABASE_KEY = ${JSON.stringify(key)};
`);
console.log(`Wrote public/config.js for ${url}`);
